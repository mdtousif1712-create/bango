def generate_transactions(count: int = 1250) -> List[Dict]:
    transactions = []
    random.seed(42)  # For reproducibility
    
    for i in range(1, count + 1):
        tid = f"TXN_{i:04d}"
        pattern = random.choice(PATTERNS)
        
        # Take full pattern or 2-3 items from pattern
        if random.random() < 0.65:
            chosen_items = list(pattern)
        else:
            k = max(2, len(pattern) - 1)
            chosen_items = random.sample(pattern, k)
                
        transactions.append({
            "transaction_id": tid,
            "items": chosen_items,
            "items_str": ",".join(chosen_items),
            "category": "Mobility Journey",
            "source": "Bengaluru Smart City Mobility & Activity Seed (Synthetic Demonstration Data)",
            "length": len(chosen_items)
        })
    return transactions

def run():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data_dir = os.path.join(base_dir, "app", "data")
    os.makedirs(data_dir, exist_ok=True)
    
    places_json_path = os.path.join(data_dir, "places.json")
    places_csv_path = os.path.join(data_dir, "places.csv")
    transactions_csv_path = os.path.join(data_dir, "transactions.csv")
    transactions_json_path = os.path.join(data_dir, "transactions.json")
    
    # 1. Write places.json
    with open(places_json_path, "w", encoding="utf-8") as f:
        json.dump(BENGALURU_PLACES, f, indent=2, ensure_ascii=False)
    print(f"Written {len(BENGALURU_PLACES)} places to {places_json_path}")
    
    # 2. Write places.csv
    fieldnames = list(BENGALURU_PLACES[0].keys())
    with open(places_csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for p in BENGALURU_PLACES:
            p_copy = dict(p)
            p_copy["tags"] = ";".join(p["tags"])
            writer.writerow(p_copy)
    print(f"Written places CSV to {places_csv_path}")
    
    # 3. Generate 1,250 transactions
    txns = generate_transactions(1250)
    
    # 4. Write transactions.csv
    with open(transactions_csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["transaction_id", "activities", "category", "source"])
        writer.writeheader()
        for t in txns:
            writer.writerow({
                "transaction_id": t["transaction_id"],
                "activities": t["items_str"],
                "category": t["category"],
                "source": t["source"]
            })
    print(f"Written {len(txns)} transactions to {transactions_csv_path}")
    
    with open(transactions_json_path, "w", encoding="utf-8") as f:
        json.dump(txns, f, indent=2, ensure_ascii=False)
        
    # 5. Populate MongoDB if reachable
    try:
        from pymongo import MongoClient
        client = MongoClient("mongodb://127.0.0.1:27017", serverSelectionTimeoutMS=2000)
        client.admin.command('ping')
        db = client["bengaluru_smart_city"]
        
        # Clean and insert places
        places_col = db["places"]
        places_col.delete_many({})
        places_col.insert_many([dict(p) for p in BENGALURU_PLACES])
        places_col.create_index("place_id", unique=True)
        places_col.create_index("category")
        places_col.create_index("name")
        print(f"Seeded {len(BENGALURU_PLACES)} places into MongoDB collection 'places'!")
        
        # Clean and insert transactions
        txns_col = db["transactions"]
        txns_col.delete_many({})
        txns_col.insert_many([dict(t) for t in txns])
        txns_col.create_index("transaction_id", unique=True)
        print(f"Seeded {len(txns)} transactions into MongoDB collection 'transactions'!")
    except Exception as e:
        print(f"MongoDB seeding notice: {e}")

if __name__ == "__main__":
    run()
